"""A4 — tables for the probe configuration (t grid, K grid), probe transfer, and the alignment diagnostic (s3 tgrid, s8, s9).
Clean reference: first 1000 cal (threshold @15%) and first 1000 test (FPR, AUROC); attacks: first 500 R50 / ViT PGD e4
(successful only); Gaussian control: first 500 R50 CTRL_gauss (all). t=1/K=8/ADM rows reuse the main scores of the same ids.
out: OUTD/analysis/a4_probe.md"""
import os, numpy as np
from scipy.stats import rankdata, spearmanr
from common import OUTD, log

def auroc(neg, pos):
    r = rankdata(np.concatenate([neg, pos])); n0, n1 = len(neg), len(pos)
    return (r[n0:].sum() - n1 * (n1 + 1) / 2) / (n0 * n1)
cl = np.load(f'{OUTD}/scores/clean.npz'); pos = {i: j for j, i in enumerate(cl['image_id'])}
def main_set(nm):
    """main (t=1, K=8, ADM) scores for the ids of a tgrid/s8 set."""
    if nm in ['cal', 'test']:
        from common import split_ids
        ids = split_ids(nm)[:1000]; return {'image_id': ids, 'cpop': cl['cpop'][[pos[i] for i in ids]]}
    c, k = ('resnet50', 'CTRL_gauss_e4') if 'CTRL' in nm else (nm.split('_PGD')[0], 'PGD_e4')
    a = np.load(f'{OUTD}/scores/adv/{c}/{k}.npz')
    return {'image_id': a['image_id'][:500], 'cpop': a['cpop'][:500], 'success': a['success'][:500]}
SETS = ['cal', 'test', 'resnet50_PGD_e4', 'vit_b_16_PGD_e4']
def row(get):
    D = {s: get(s) for s in SETS + ['resnet50_CTRL_gauss_e4'] if get(s) is not None}
    t = np.quantile(-D['cal']['cpop'], 0.85); out = [f"{np.mean(-D['test']['cpop'] > t):.3f}"]
    for s in ['resnet50_PGD_e4', 'vit_b_16_PGD_e4']:
        m = D[s]['success']; p = -D[s]['cpop'][m]; out += [f"{auroc(-D['test']['cpop'], p):.3f}", f'{np.mean(p > t):.3f}']
    if 'resnet50_CTRL_gauss_e4' in D:
        p = -D['resnet50_CTRL_gauss_e4']['cpop']; out += [f"{auroc(-D['test']['cpop'], p):.3f}", f'{np.mean(p > t):.3f}']
    out.append(f"{np.median(D['test']['cpop']):.4f}")
    return out
md = ['# A4 probe configuration / transfer / alignment (auto-generated by a4_probe.py)\n']
head = '| setting | FPR@15 (test) | R50 AUROC | R50 TPR | ViT AUROC | ViT TPR | gauss AUROC | gauss TPR | median clean cpop |'
md += ['## t grid (ADM, sigma=0.005, K=8)\n', head, '|' + '---|' * 9]
for t in [0, 1, 2, 4]:
    def g(s, t=t):
        if s == 'resnet50_CTRL_gauss_e4': return None
        if t == 1: return main_set(s)
        f = f'{OUTD}/scores/tgrid/{s}_t{t}.npz'; return dict(np.load(f)) if os.path.exists(f) else None
    try: md.append(f'| t={t} | ' + ' | '.join(row(g)) + ' |')
    except Exception as e: md.append(f'| t={t} | missing ({e}) |')
md += ['\n## K grid (ADM, t=1, sigma=0.005)\n', head, '|' + '---|' * 9]
for k in [1, 2, 4, 8, 16]:
    def g(s, k=k):
        if k == 8: return main_set(s)
        f = f'{OUTD}/scores/kgrid/{s}_k{k}.npz'; return dict(np.load(f)) if os.path.exists(f) else None
    try: md.append(f'| K={k} | ' + ' | '.join(row(g)) + ' |')
    except Exception as e: md.append(f'| K={k} | missing ({e}) |')
md += ['\n## probe transfer (t=1, sigma=0.005, K=8)\n', head, '|' + '---|' * 9]
for p in ['adm', 'celebahq', 'church']:
    def g(s, p=p):
        if p == 'adm': return main_set(s)
        f = f'{OUTD}/scores/probe/{p}/{s}.npz'; return dict(np.load(f)) if os.path.exists(f) else None
    try: md.append(f'| {p} | ' + ' | '.join(row(g)) + ' |')
    except Exception as e: md.append(f'| {p} | missing ({e}) |')
try:   # cross-probe rank correlation on clean test + R50 adv
    for s in ['test', 'resnet50_PGD_e4']:
        a = main_set(s)['cpop']; b = np.load(f'{OUTD}/scores/probe/celebahq/{s}.npz')['cpop']; c = np.load(f'{OUTD}/scores/probe/church/{s}.npz')['cpop']
        md.append(f'\nSpearman {s}: ADM-CelebA {spearmanr(a, b)[0]:.3f}, ADM-Church {spearmanr(a, c)[0]:.3f}, CelebA-Church {spearmanr(b, c)[0]:.3f}')
except Exception as e: md.append(f'\nspearman missing ({e})')
md += ['\n## alignment diagnostic (ResNet-50 deltas, first 300 per kind; medians; attacks successful only)\n', '| input | cos(eps_hat(x\'), d) | cos(eps_hat(x\'), eps_hat(x)) | energy share along d | norm ratio | cpop ratio | Spearman(cos_dn, log cpop ratio) |', '|---|---|---|---|---|---|---|']
pool = [[], []]
for k in ['PGD_e4', 'FGSM_e4', 'TIFGSM_e4', 'Square_e4', 'CW_e4'] + [f'CTRL_{c}_e4' for c in ['sign', 'gauss', 'phase', 'shuffle', 'jpeg75', 'blur']]:
    f = f'{OUTD}/scores/align/{k}.npz'
    if not os.path.exists(f): md.append(f'| {k} | missing |'); continue
    d = np.load(f); m = d['success'] if not k.startswith('CTRL') else np.ones(len(d['success']), bool)
    a = np.load(f'{OUTD}/scores/adv/resnet50/{k}.npz'); ap = {i: j for j, i in enumerate(a['image_id'])}
    r = np.log(a['cpop'][[ap[i] for i in d['image_id']]] / cl['cpop'][[pos[i] for i in d['image_id']]])
    pool[0].append(d['cos_dn'][m]); pool[1].append(r[m])
    md.append(f'| {k} | ' + ' | '.join(f'{np.median(d[x][m]):.3f}' for x in ['cos_dn', 'cos_base', 'frac', 'norm_ratio'])
              + f' | {np.median(np.exp(r[m])):.3f} | {spearmanr(d["cos_dn"][m], r[m])[0]:.3f} |')
if pool[0]: md.append(f'\npooled Spearman(cos_dn, log cpop ratio) over all inputs: {spearmanr(np.concatenate(pool[0]), np.concatenate(pool[1]))[0]:.3f}')
open(f'{OUTD}/analysis/a4_probe.md', 'w').write('\n'.join(md) + '\n'); print('\n'.join(md))
