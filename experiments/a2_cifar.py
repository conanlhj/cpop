"""A2 — CIFAR-10 tables (Table 8 + benign controls) from s7/s5 outputs. CPU, light.
Thresholds from clean P_cal (3000), FPR on clean P_test (3000); TPR over successful AEs (controls: over all inputs).
Scores oriented higher = more suspicious (probe cpop negated). Mean over the six classifiers.
out: OUTD/analysis/a2_cifar.md"""
import os, numpy as np, pandas as pd
from scipy.stats import rankdata
from common import OUTD, log

CL = ['resnet20', 'resnet56', 'vgg16_bn', 'mobilenetv2', 'repvgg_a2', 'shufflenetv2']
ATK = ['FGSM', 'BIM', 'PGD', 'MIFGSM', 'APGD', 'AutoAttack', 'CW', 'DeepFool', 'Square']
CTRL = ['CTRL_sign', 'CTRL_gauss', 'CTRL_phase', 'CTRL_shuffle', 'CTRL_jpeg75', 'CTRL_blur']
DETS = ['cpop', 'fs_common', 'lid', 'maha_cc', 'kde_cc']
OD = f'{OUTD}/cifar'; spl = pd.read_csv(f'{OD}/splits.csv').set_index('image_id').split
def auroc(neg, pos):
    r = rankdata(np.concatenate([neg, pos])); n0, n1 = len(neg), len(pos)
    return (r[n0:].sum() - n1 * (n1 + 1) / 2) / (n0 * n1)
pc = np.load(f'{OD}/probe_clean.npz'); psp = spl.loc[pc['image_id']].values

def clean(c):
    S = {'cpop': {s: -pc['cpop'][psp == s].astype(np.float64) for s in ['cal', 'test']}}
    k = np.load(f'{OD}/{c}/clean.npz'); ksp = spl.loc[k['image_id']].values
    f = np.load(f'{OD}/feat_scores/{c}/clean.npz', allow_pickle=True); fsp = f['split'].astype(str)
    S['fs_common'] = {s: k['fs_common'][ksp == s].astype(np.float64) for s in ['cal', 'test']}
    for d in ['lid', 'maha_cc', 'kde_cc']: S[d] = {s: f[d][fsp == s].astype(np.float64) for s in ['cal', 'test']}
    return S, float((k['pred'][ksp == 'test'] == k['label'][ksp == 'test']).mean())
def adv(c, a):
    k = np.load(f'{OD}/{c}/{a}.npz'); f = np.load(f'{OD}/feat_scores/{c}/{a}.npz'); assert (f['image_id'] == k['image_id']).all()
    o = {'success': k['success'], 'cpop': -k['probe_cpop'].astype(np.float64), 'fs_common': k['fs_common'].astype(np.float64)}
    for d in ['lid', 'maha_cc', 'kde_cc']: o[d] = f[d].astype(np.float64)
    return o
CS = {c: clean(c) for c in CL}
md = ['# A2 CIFAR-10 tables (auto-generated by a2_cifar.py)\n',
      'clean test accuracy: ' + ', '.join(f'{c} {CS[c][1]:.3f}' for c in CL) + '\n',
      f'CPOP realised P_test FPR @15%: {np.mean(CS[CL[0]][0]["cpop"]["test"] > np.quantile(CS[CL[0]][0]["cpop"]["cal"], .85)):.3f}\n']
md.append('| input | n/clf | succ | ' + ' | '.join(f'{d} TPR@15 / AUROC' for d in DETS) + ' |'); md.append('|' + '---|' * (3 + len(DETS)))
for a in ATK + CTRL:
    row = {d: ([], []) for d in DETS}; ns, sr = [], []
    for c in CL:
        A = adv(c, a); S = CS[c][0]; m = A['success'] if not a.startswith('CTRL') else np.ones_like(A['success'])
        ns.append(len(m)); sr.append(A['success'].mean())
        for d in DETS:
            p = A[d][m]; row[d][0].append(np.mean(p > np.quantile(S[d]['cal'], .85))); row[d][1].append(auroc(S[d]['test'], p))
    md.append(f'| {a} | {int(np.mean(ns))} | {np.mean(sr):.3f} | ' + ' | '.join(f'{np.mean(row[d][0]):.3f} / {np.mean(row[d][1]):.3f}' for d in DETS) + ' |')
md.append('\nControls: TPR = flag rate over all perturbed inputs; succ = fraction whose label flipped.')
open(f'{OUTD}/analysis/a2_cifar.md', 'w').write('\n'.join(md) + '\n'); log('wrote a2')
